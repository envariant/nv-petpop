#!/usr/bin/env python3
"""Write fixtures/library/golden.json: stamps painted with the Python rasteriser (the export's) and the sha256 of
the resulting RGBA stamp layer. packages/viewer/src/stamps.test.ts paints the same stamps with the kiosk's
TypeScript port and must produce the same bytes, which is what makes the print match the screen.
tests/unit/test_library_paint.py fails if this file is stale.

    python scripts/make_library_golden.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import backend  # noqa: E402,F401  (puts packages/*/python on sys.path)

from petpop_library import paint  # noqa: E402
from petpop_library.atlas import texel_map  # noqa: E402
from petpop_library.deltas import mirror_x  # noqa: E402
from petpop_library.meshkit import load_base  # noqa: E402

OUT = ROOT / "fixtures" / "library" / "golden.json"
SIZE = 1024


def golden_stamps(species: str) -> list[dict]:
    """Stamps on seams (chin, back of the head, under the tail), overlapping, mirrored, and a brush stroke."""
    base = load_base(species)
    lm = {k: [round(float(x), 3) for x in base.co[v]] for k, v in base.landmarks.items()}
    stamps = [
        {"p": lm["chin"], "r": 5.0, "colour": "#2266FF"},
        {"p": lm["back_of_head"], "r": 7.5, "colour": "#22AA44"},
        {"p": lm["tail_tip"], "r": 3.0, "colour": "#AA2222"},
        {"p": lm["eye_L"], "r": 4.0, "colour": "#F4EFE6"},
        {"p": mirror_x(lm["eye_L"]), "r": 4.0, "colour": "#F4EFE6"},
    ]
    a, b = base.co[base.landmarks["neck_front"]], base.co[base.landmarks["paw_FL"]]
    for i in range(8):  # brush: small overlapping dabs along a line
        p = a + (b - a) * (i / 7)
        stamps.append({"p": [round(float(x), 3) for x in p], "r": 1.5, "colour": "#1E1B1A"})
    return stamps


def golden(species: str) -> dict:
    # The proxy release's one mesh is the template itself (decision 118), so its texel map is the species map.
    base = load_base(species)
    stamps = golden_stamps(species)
    layer = paint.stamp_layer(base, texel_map(species, SIZE), stamps)
    return {"species": species, "size": SIZE, "stamps": stamps, "rgba_sha256": hashlib.sha256(layer.tobytes()).hexdigest(),
            "painted_texels": int((layer[..., 3] > 0).sum())}


def build() -> dict:
    return {"note": "Generated by scripts/make_library_golden.py. Do not edit.", "release": "release-dog-1.tar", "cases": [golden("dog")]}


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(build(), indent=1) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
