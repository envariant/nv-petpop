#!/usr/bin/env bash
# Regenerate the Mac's hash-locked Python requirements (mac/locks/*.txt) from mac/locks/*.in.
# Runs anywhere uv runs (the cloud VM included): it resolves for macOS 15+ arm64 and the pinned Python without
# installing anything. Wheels only (--only-binary), so nothing is compiled on the Mac. EXCLUDE_NEWER freezes the
# package index at a date, so re-running gives the same lock; move it forward (and re-run) to take upgrades,
# then commit the .in and .txt changes together.
#
#   mac/lock.sh            # or: make -C mac lock
set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
LOCKS="$REPO/mac/locks"
EXCLUDE_NEWER="2026-10-28T00:00:00Z"
export MACOSX_DEPLOYMENT_TARGET=15.0   # M4 Macs ship with macOS 15; torch 2.13 wheels need 14+
PY="$(awk '$1=="python" {print $2}' "$REPO/mac/tools.lock")"
COMFY_COMMIT="$(awk '$1=="ComfyUI" {print $3}' "$REPO/pipelines/comfy/requirements.txt")"

# ComfyUI's own requirements at the pinned commit. torchaudio is left out: its macOS wheels lag torch (2.11 vs
# 2.13, a binary mismatch), ComfyUI does not require it, and no PetPop workflow uses audio.
{
  echo "# ComfyUI venv on the Mac. Generated by mac/lock.sh from ComfyUI's requirements.txt at $COMFY_COMMIT;"
  echo "# torch is held to the shape venv's version so the two venvs run the same MPS build."
  echo "torch==2.13.*"
  curl -fsSL "https://raw.githubusercontent.com/comfyanonymous/ComfyUI/$COMFY_COMMIT/requirements.txt"
  # ComfyUI-MVAdapter (pinned in pipelines/comfy/requirements.txt). Its own requirements.txt pins diffusers 0.31 and
  # transformers 4.46, which ComfyUI's transformers>=4.50.3 rules out; current releases still carry the diffusers
  # internals it imports (convert_from_ckpt, _get_model_file), so its packages are taken unpinned here instead.
  echo "# ComfyUI-MVAdapter"
  printf '%s\n' diffusers peft accelerate omegaconf trimesh   # the packages its code imports
} > "$LOCKS/comfyui.in"

for name in comfyui shape tools; do
  uv pip compile "$LOCKS/$name.in" -o "$LOCKS/$name.txt" --quiet \
    --python-platform aarch64-apple-darwin --python-version "$PY" \
    --exclude-newer "$EXCLUDE_NEWER" --generate-hashes --only-binary :all: --no-header --index-url https://pypi.org/simple
  { echo "# Generated by mac/lock.sh from $name.in for macOS 15+ arm64, Python $PY, index as of $EXCLUDE_NEWER. Do not edit."
    cat "$LOCKS/$name.txt"; } > "$LOCKS/$name.txt.tmp" && mv "$LOCKS/$name.txt.tmp" "$LOCKS/$name.txt"
  echo "$name: $(grep -c '^[a-zA-Z0-9]' "$LOCKS/$name.txt") packages"
done
